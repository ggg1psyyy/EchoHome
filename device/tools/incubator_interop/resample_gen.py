"""Taps and vectors for internal/incubator's Upsampler, from the controller's
own em_resample (the reference the Go port is held to).

    python -I resample_gen.py <controller dir> <device/internal/incubator>

Writes resample_taps.go (the three phases of the prototype low-pass, as
em_resample._design computes them, printed exactly) and
testdata/resample_{in,out}.bin: seeded audio in integers (a sweep, steps,
full-scale edges) and what em_resample makes of it, flushed. Needs numpy.
"""
import struct
import sys
from pathlib import Path

ctrl, out = Path(sys.argv[1]), Path(sys.argv[2])
sys.path.insert(0, str(ctrl))
import em_resample as rs  # noqa: E402

phases = rs._PHASES
lines = ["// Generated by tools/incubator_interop/resample_gen.py from the controller's",
         "// em_resample._design; do not edit.", "", "package incubator", "",
         f"const tapsPerPhase = {rs.TAPS_PER_PHASE}", "",
         f"var phases = [{rs.FACTOR}][tapsPerPhase]float64{{"]
for p in phases:
    lines.append("\t{" + ", ".join(repr(float(v)) for v in p) + "},")
lines.append("}")
(out / "resample_taps.go").write_text("\n".join(lines) + "\n")

# Seeded input, in integers so it is the same bytes everywhere.
x, state = [], 0x5EED
for i in range(16000 * 2):
    state = (state * 1103515245 + 12345) & 0x7FFFFFFF
    noise = (state >> 16) % 4001 - 2000
    sweep = ((i * (i // 40)) % 32768) - 16384  # a rising, buzzy sweep
    v = noise + (sweep // 4)
    if 20000 <= i < 20400:
        v = 32767 if (i // 20) % 2 else -32768  # full-scale square: clipping
    x.append(max(-32768, min(32767, v)))
pcm = struct.pack(f"<{len(x)}h", *x)
up = rs.Upsampler()
y = up.process(pcm) + up.flush()
(out / "testdata").mkdir(exist_ok=True)
(out / "testdata" / "resample_in.bin").write_bytes(pcm)
(out / "testdata" / "resample_out.bin").write_bytes(y)
print(f"{len(x)} samples in, {len(y) // 2} out")
