// Command esphome_gen generates internal/esphome/api from ESPHome's native
// API definitions as aioesphomeapi compiles them: the descriptors beside it
// (descriptors/*.pb) are api.proto and api_options.proto as aioesphomeapi
// 46.25.0 (MIT) compiles them, the version Home Assistant 2026.11 pins:
// pulled out of its api_pb2.py and api_options_pb2.py by extract_pb.py,
// which parses the AddSerializedFile literal and never imports the module
// (sdist sha256 02bde168ad623e039a8284a2802e0b49fd05f6915261a45b3bff57657536de8b).
// 45.3.1, the controller's vendored copy,
// lacked api_encryption_provisionable, which HA reads to set a key itself.
// No protoc: the descriptors go straight to protoc-gen-go's own generator.
//
// To move to another version: download its sdist, check its sha256, run
//
//	python3 -I tools/esphome_gen/extract_pb.py <pkg>/aioesphomeapi/api_pb2.py tools/esphome_gen/descriptors/api.pb
//
// (and api_options), update the pins below and regenerate.
//
//	go run ./tools/esphome_gen            (from device/)
//
// It writes api.pb.go and api_options.pb.go, and msgids.go: each message's
// wire id, from its (id) option (api_options.proto: MessageOptions field
// 1036), as the protocol frames them.
package main

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"

	gengo "google.golang.org/protobuf/cmd/protoc-gen-go/internal_gengo"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/encoding/protowire"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protodesc"
	"google.golang.org/protobuf/types/descriptorpb"
	"google.golang.org/protobuf/types/pluginpb"
)

const (
	goPackage = "github.com/wilbowes/EchoMuse/internal/esphome/api"
	out       = "internal/esphome/api"
	src       = "tools/esphome_gen/descriptors"
	// idOption is api_options.proto's `extend google.protobuf.MessageOptions
	// { optional uint32 id = 1036; }`.
	idOption = 1036
)

// pinned are the descriptors' sha256: a changed file is a protocol change,
// to be made on purpose (update the controller's vendored copy with it).
var pinned = map[string]string{
	"api_options.pb": "c5fcfdd21e545ba0",
	"api.pb":         "d2af7462382cc1fd",
}

func load(name string) *descriptorpb.FileDescriptorProto {
	b, err := os.ReadFile(filepath.Join(src, name))
	if err != nil {
		log.Fatal(err)
	}
	sum := sha256.Sum256(b)
	if got := hex.EncodeToString(sum[:])[:16]; got != pinned[name] {
		log.Fatalf("%s: sha256 %s, pinned %s", name, got, pinned[name])
	}
	fd := &descriptorpb.FileDescriptorProto{}
	if err := proto.Unmarshal(b, fd); err != nil {
		log.Fatal(err)
	}
	fd.Options = &descriptorpb.FileOptions{GoPackage: proto.String(goPackage + ";api")}
	return fd
}

func main() {
	opts := load("api_options.pb")
	api := load("api.pb")
	// Before the generator sees them: it resolves the options against the
	// files it is given, and the (id) option is then no longer unknown.
	writeIDs(proto.Clone(api).(*descriptorpb.FileDescriptorProto))
	desc := protodesc.ToFileDescriptorProto(descriptorpb.File_google_protobuf_descriptor_proto)
	req := &pluginpb.CodeGeneratorRequest{
		FileToGenerate: []string{"api_options.proto", "api.proto"},
		Parameter:      proto.String("paths=source_relative"),
		ProtoFile:      []*descriptorpb.FileDescriptorProto{desc, opts, api},
	}
	plugin, err := protogen.Options{}.New(req)
	if err != nil {
		log.Fatal(err)
	}
	for _, f := range plugin.Files {
		if f.Generate {
			gengo.GenerateFile(plugin, f)
		}
	}
	resp := plugin.Response()
	if resp.Error != nil {
		log.Fatal(*resp.Error)
	}
	for _, f := range resp.File {
		path := filepath.Join(out, f.GetName())
		if err := os.WriteFile(path, []byte(f.GetContent()), 0o644); err != nil {
			log.Fatal(err)
		}
		fmt.Println("wrote", path)
	}
}

// writeIDs writes msgids.go: message name to wire id, from each message's
// (id) option (kept by the descriptor as an unknown field of its options).
func writeIDs(api *descriptorpb.FileDescriptorProto) {
	type entry struct {
		name string
		id   uint64
	}
	var all []entry
	for _, m := range api.MessageType {
		raw := m.GetOptions().ProtoReflect().GetUnknown()
		for len(raw) > 0 {
			num, typ, n := protowire.ConsumeTag(raw)
			if n < 0 {
				log.Fatalf("%s: bad options", m.GetName())
			}
			raw = raw[n:]
			if num == idOption && typ == protowire.VarintType {
				v, k := protowire.ConsumeVarint(raw)
				all = append(all, entry{m.GetName(), v})
				raw = raw[k:]
				continue
			}
			k := protowire.ConsumeFieldValue(num, typ, raw)
			if k < 0 {
				log.Fatalf("%s: bad options", m.GetName())
			}
			raw = raw[k:]
		}
	}
	sort.Slice(all, func(i, j int) bool { return all[i].id < all[j].id })
	var b strings.Builder
	b.WriteString("// Code generated by tools/esphome_gen. DO NOT EDIT.\n\npackage api\n\n")
	b.WriteString("// MessageIDs is each message's wire id (its (id) option), by message name.\n")
	b.WriteString("var MessageIDs = map[string]uint32{\n")
	for _, e := range all {
		fmt.Fprintf(&b, "\t%q: %d,\n", e.name, e.id)
	}
	b.WriteString("}\n")
	path := filepath.Join(out, "msgids.go")
	if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Println("wrote", path, len(all), "ids")
}
