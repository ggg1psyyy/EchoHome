#!/bin/sh
# Re-vendors the audio front end the Voice Incubator firmware feeds its wake
# word models: esphome/esp-micro-speech-features 1.2.3 (TensorFlow Lite
# Micro's microfrontend, fixed point, Apache-2.0), byte-identical to the ESP
# component registry's release, plus one wrapper .c per source here (cgo
# compiles only .c files in this directory, and a wrapper keeps the sources'
# relative includes resolving). Run from this directory; it replaces libmsf/
# and the wrappers.
set -eu
VER=1.2.3
SHA=052a8f32e7a82f49593bfdc067638a8cee6542443726d1a7e5b01b3bd9d67eac
URL="https://components-file.espressif.com/components/esphome/esp-micro-speech-features/$VER/esphome__esp-micro-speech-features-v$VER.zip"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
curl -fsSL -o "$tmp/msf.zip" "$URL"
echo "$SHA  $tmp/msf.zip" | sha256sum -c -
python3 -c 'import sys, zipfile; zipfile.ZipFile(sys.argv[1]).extractall(sys.argv[2])' "$tmp/msf.zip" "$tmp/msf"
rm -rf libmsf zz_*.c
mkdir -p libmsf/include libmsf/src
cp "$tmp/msf/LICENSE" "$tmp/msf/README.md" libmsf/
cp "$tmp/msf/include/"*.h libmsf/include/
cp "$tmp/msf/src/"*.c "$tmp/msf/src/"*.h libmsf/src/
for f in libmsf/src/*.c; do
	name="zz_$(basename "${f%.c}")"
	printf '// Generated by vendor.sh; do not edit.\n#include "%s"\n' "$f" > "$name.c"
done
echo "esp-micro-speech-features $VER vendored: $(ls libmsf/src/*.c | wc -l) sources"
